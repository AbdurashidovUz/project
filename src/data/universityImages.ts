/**
 * Get the best image URL for a university.
 * Priority: named map → country pool → generic pool (deterministic by name hash)
 */
export function getUniversityImageUrl(
  universityName: string,
  country: string
): string {
  // 1. Named exact match
  if (universityImages[universityName]) {
    return universityImages[universityName];
  }

  // 2. Country-themed pool (deterministic pick based on name)
  const pool = countryImages[country];
  if (pool && pool.length > 0) {
    const hash = universityName.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
    return pool[hash % pool.length];
  }

  // 3. Generic campus pool
  const hash = universityName.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  return genericCampusImages[hash % genericCampusImages.length];
}
